// Generates LICENSES-ASSETS.md from sources.json: one row per source, with the manifest entries that use it.
import fs from 'node:fs';

const LICENSES = {
  CC0: { name: 'CC0 1.0 Universal (public domain)', url: 'https://creativecommons.org/publicdomain/zero/1.0/' },
  'CC-BY': { name: 'Creative Commons Attribution', url: 'https://creativecommons.org/licenses/by/4.0/' },
};

const cell = (s) => String(s).replaceAll('|', '\\|');

/** The speech is not built from sources.json: `npm run speech` renders it (scripts/assets/speech). */
const SPEECH = [
  '## Speech',
  '',
  'Every clip under `src/assets/speech/` is rendered by `npm run speech` from original lines (scripts/assets/speech) with the model and voices below.',
  '',
  '| Model | Author | Source | License | Used by |',
  '| --- | --- | --- | --- | --- |',
  '| Kokoro-82M v1.0 and its voices | hexgrad | https://huggingface.co/hexgrad/Kokoro-82M | Apache-2.0 | speech/*.mp3 |',
];

export function writeLicenses(sources, entries, file) {
  const usedBy = new Map();
  for (const e of entries) {
    if (!usedBy.has(e.license)) usedBy.set(e.license, []);
    usedBy.get(e.license).push(e.id);
  }
  const lines = [
    '# Asset licenses',
    '',
    'Generated by `npm run assets` from `scripts/assets/sources.json`. Do not edit by hand.',
    '',
    'Every model, texture and HDRI under `src/assets/` comes from a source below. The raw downloads are not committed; `npm run assets:fetch` downloads them and checks their hashes.',
    'The assets are used under CC0 (no attribution required, credited here anyway) or CC-BY (attribution required, see the Credit column).',
    '',
    `- CC0: ${LICENSES.CC0.name}, ${LICENSES.CC0.url}`,
    `- CC-BY: ${LICENSES['CC-BY'].name}, ${LICENSES['CC-BY'].url}`,
    '',
    '| ID | Asset | Author | Source | License | Credit | Used by |',
    '| --- | --- | --- | --- | --- | --- | --- |',
  ];
  for (const s of sources) {
    if (!LICENSES[s.license]) throw new Error(`${s.id}: license ${s.license} is not allowed (CC0 or CC-BY only)`);
    if (s.license === 'CC-BY' && !s.credit) throw new Error(`${s.id}: CC-BY sources need a credit`);
    const ids = usedBy.get(s.id) ?? [];
    // Every id is named, never truncated: the table is the per-asset license record.
    lines.push(`| ${cell(s.id)} | ${cell(s.name)} | ${cell(s.author)} | ${s.page} | ${s.license} | ${cell(s.credit ?? '')} | ${cell(ids.join(', '))} |`);
  }
  lines.push('', ...SPEECH, '');
  fs.writeFileSync(file, lines.join('\n'));
}
